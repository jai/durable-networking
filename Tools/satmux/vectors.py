#!/usr/bin/env python3
"""Prints SatmuxVectors.swift: keys, frames and digests made by satmux.py's own code, for SatmuxWireTests."""
import hashlib
import hmac
import os
import struct
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import satmux  # noqa: E402

psk = bytes(range(32))
nonce = bytes(range(100, 132))
session = bytes(range(200, 216))
c2s, s2c = satmux.derive_keys(psk, nonce, session)
hello = session + hmac.new(psk, b"ORB-MUX-V3" + nonce + session, hashlib.sha256).digest()
proof = hmac.new(psk, b"ORB-MUX-V3-OK" + nonce + session, hashlib.sha256).digest()

# A fetch frame as satmux's 1-RTT gate sends it (handle_fast_1rtt), stream 3, seq 1.
request = "\n".join(["GET", "https://example.test/v1/items?x=1", "Authorization: Bearer t0ken"]).encode()
fetch = struct.pack(satmux.HDR_FMT, satmux.FT_FETCH, 3, 0)
sealed = struct.pack("!Q", 1) + satmux.xor_keystream(c2s, 1, zlib.compress(request, 6))
fetch = struct.pack(satmux.HDR_FMT, satmux.FT_FETCH, 3, len(sealed)) + sealed

# The relay's answer as handle_ground_fetch sends it: the response, encrypted, on the same stream, then FIN.
relay = satmux.CarrierConn(1, None, None, True, s2c, c2s)
relay.tx_seq = 4  # the relay has sent four encrypted frames on this carrier already
body = b'{"items":[' + b",".join(b'{"id":%d,"title":"item %d"}' % (i, i) for i in range(400)) + b"]}"
response = (
    b"HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nSet-Cookie: a=1\r\nSet-Cookie: b=2\r\n"
    + b"Content-Length: %d\r\nConnection: close\r\nX-Orb-Sat-Mux: 1-RTT-Ground-TLS\r\n\r\n" % len(body)
    + body
)
answer = [relay.pack_data(3, response[i : i + satmux.MAX_CHUNK], encrypt=True, level=6)
          for i in range(0, len(response), satmux.MAX_CHUNK)]
answer.append(struct.pack(satmux.HDR_FMT, satmux.FT_FIN, 3, 0))

key = bytes(range(64, 96))
keyed = {n: hashlib.blake2b(bytes(i % 251 for i in range(n)), key=key, digest_size=64).hexdigest()
         for n in (0, 1, 64, 127, 128, 129, 255, 256, 1000)}
keystream = satmux.xor_keystream(key, 7, bytes(200)).hex()


def lit(b: bytes) -> str:
    return '"' + b.hex() + '"'


print("// Generated by Tools/satmux/vectors.py from satmux.py's own code. Do not edit.")
print("// swiftlint:disable all")
print("enum SatmuxVectors {")
print(f"    static let psk = {lit(psk)}")
print(f"    static let nonce = {lit(nonce)}")
print(f"    static let session = {lit(session)}")
print(f"    static let clientToRelay = {lit(c2s)}")
print(f"    static let relayToClient = {lit(s2c)}")
print(f"    static let hello = {lit(hello)}")
print(f"    static let proof = {lit(proof)}")
print(f"    static let request = {lit(request)}")
print(f"    static let fetchFrame = {lit(fetch)}")
print(f"    static let responseBody = {lit(body)}")
print("    static let answerFrames = [")
for frame in answer:
    print(f"        {lit(frame)},")
print("    ]")
print(f"    static let blakeKey = {lit(key)}")
print("    /// BLAKE2b-512 under `blakeKey` of bytes `i % 251` for i in 0..<n.")
print("    static let keyedDigests: [Int: String] = [")
for n, digest in keyed.items():
    print(f'        {n}: "{digest}",')
print("    ]")
print("    /// satmux's keystream under `blakeKey`, seq 7, 200 bytes.")
print(f'    static let keystream = "{keystream}"')
print("}")
